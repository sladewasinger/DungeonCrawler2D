/** JSON preset round-trip importer and copy-pasteable @dc2d/client game TypeScript snippet formatter. */
import { normalizeTrackSpec } from "../../audio/proceduralSynth.js";
import type { SoundTrackSpec } from "../studioTypes.js";

export type ImportParseResult =
  | { readonly ok: true; readonly name?: string | undefined; readonly description?: string | undefined; readonly tracks: SoundTrackSpec[] }
  | { readonly ok: false; readonly error: string };

export function formatGameCodeSnippet(name: string, tracks: readonly SoundTrackSpec[]): string {
  const safeVar = (name.toUpperCase().replace(/[^A-Z0-9]+/g, "_").replace(/^_|_$/g, "") || "CUSTOM_SFX") + "_TRACKS";
  const safeFn = "play" + (name.replace(/[^a-zA-Z0-9]+/g, "") || "CustomSfx");
  const json = JSON.stringify(tracks, null, 2);
  return [
    `// Generated by DungeonCrawler 2D Sound Studio (${name})`,
    `import { playProceduralTracks, type ProceduralTrackSpec } from "./proceduralSynth.js";`,
    ``,
    `export const ${safeVar}: readonly ProceduralTrackSpec[] = ${json};`,
    ``,
    `export function ${safeFn}(ctx: AudioContext, dst: AudioNode): void {`,
    `  playProceduralTracks({ ctx, dst, tracks: ${safeVar} });`,
    `}`,
  ].join("\n");
}

function extractRawList(parsed: unknown): {
  readonly list: unknown[] | null; readonly name?: string | undefined; readonly description?: string | undefined;
} {
  if (Array.isArray(parsed)) return { list: parsed };
  if (!parsed || typeof parsed !== "object") return { list: null };
  const obj = parsed as Record<string, unknown>;
  const list = Array.isArray(obj.tracks) ? obj.tracks : null;
  return {
    list,
    name: typeof obj.name === "string" ? obj.name : undefined,
    description: typeof obj.description === "string" ? obj.description : undefined,
  };
}

export function parseImportedPresetJson(raw: string): ImportParseResult {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return { ok: false, error: "Invalid JSON syntax — paste an array of tracks or { name, tracks } JSON." };
  }
  const { list, name, description } = extractRawList(parsed);
  if (!list || list.length === 0) {
    return { ok: false, error: "Expected a non-empty tracks array." };
  }
  const tracks = list
    .filter((item): item is Partial<SoundTrackSpec> => Boolean(item && typeof item === "object"))
    .map((item, idx) => normalizeTrackSpec(item, `imp-${Date.now().toString(36)}-${idx + 1}`));
  if (tracks.length === 0) return { ok: false, error: "No valid track objects found inside JSON." };
  return { ok: true, name, description, tracks };
}

function makeDrawerBtn(label: string, cls: string, onClick: () => void): HTMLButtonElement {
  const b = document.createElement("button");
  b.type = "button";
  b.className = cls;
  b.textContent = label;
  b.addEventListener("click", () => { b.blur(); onClick(); });
  return b;
}

export function triggerWavDownload(presetName: string, blob: Blob): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${presetName.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.wav`;
  a.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function buildImportDrawer(onImport: (raw: string) => string | null): {
  readonly el: HTMLDivElement; readonly open: () => void;
} {
  const drawer = document.createElement("div");
  drawer.className = "st-import-drawer";
  drawer.hidden = true;
  const area = document.createElement("textarea");
  area.className = "st-import-area";
  area.placeholder = "Paste preset JSON exported by Copy JSON...";
  const errEl = document.createElement("span");
  errEl.className = "st-sub";

  const loadBtn = makeDrawerBtn("Load JSON", "st-btn st-btn-save", () => {
    const err = onImport(area.value);
    if (err) { errEl.textContent = err; return; }
    drawer.hidden = true;
    errEl.textContent = "";
    area.value = "";
  });
  const closeBtn = makeDrawerBtn("Close", "st-btn", () => { drawer.hidden = true; errEl.textContent = ""; });
  const bar = document.createElement("div");
  bar.className = "st-bar";
  bar.append(loadBtn, closeBtn, errEl);
  drawer.append(area, bar);

  return {
    el: drawer,
    open: () => {
      drawer.hidden = !drawer.hidden;
      if (!drawer.hidden) area.focus();
    },
  };
}
